class PythonTemplates:
    """Python code of a new layer: converter, serializer, emitter, test model, registry entries."""

    HEADER = (
        "# SPDX-License-Identifier: BSD-3-Clause\n"
        "# Copyright (c) 2010-2024, ITU/ISO/IEC. See LICENSE in the repository root.\n"
    )

    def __init__(self, spec):
        self.spec = spec

    # --- onnx2sadl/ops/xxx_converter.py -----------------------------------------
    def converter(self):
        s = self.spec
        base_class, base_module = {
            "unary": ("UnaryConverter", "unary_converter"),
            "binary": ("BinaryConverter", "binary_converter"),
            "op": ("OpConverter", "op_converter"),
        }[s.converter_base]
        uses_error = bool(s.params) or s.converter_base == "op" and bool(s.const_inputs)
        imports = []
        if uses_error:
            imports.append("from ..errors.conversion_error import ConversionError")
        imports.append("from ..types.op_type import OpType")
        imports.append(f"from .{base_module} import {base_class}")
        ops = ", ".join(f'"{o}"' for o in s.onnx_ops) + ("," if len(s.onnx_ops) == 1 else "")

        body = [
            "",
            "",
            "",
            f"class {s.name}Converter({base_class}):",
            f'    """ONNX {", ".join(s.onnx_ops)} -> SADL {s.name}, generated by tools/new_layer.py.',
            "",
            f"    {s.marker}: check the conversion (CONTRIBUTE.md 4.2, 4.3).",
            '    """',
            "",
            f"    onnx_ops = ({ops})",
        ]
        if s.converter_base != "op":
            body.append(f"    sadl_op = OpType.{s.name}")
        if s.converter_base == "binary":
            body += [
                "    # BinaryConverter options (see binary_converter.py):",
                '    # const_to_transpose = "producer"; reject_two_constants = True;',
                "    # const_first_swaps = True; lower_rank_swaps = True",
            ]
        if s.converter_base == "op":
            body += self._op_convert()
        elif s.params:
            body += self._layer_attrs()
        if s.layout == "axis":
            body += self._axis_note()
        if s.layout == "transpose":
            body += self._annotate()
        if s.params:
            body += self._required_attribute()
        return self.HEADER + "\n" + "\n".join(imports) + "\n".join(body) + "\n"

    def _attrs_dict(self, indent):
        lines = []
        for p in self.spec.params:
            lines.append(f'{indent}    "{p.name}": {p.onnx_value(f"self._required(node, {chr(34)}{p.name}{chr(34)})")},')
        return lines

    def _layer_attrs(self):
        s = self.spec
        order = ", ".join(p.name for p in s.params)
        return [
            "",
            "    def layer_attrs(self, node):",
            f"        # {s.marker}: map the ONNX attributes to the SADL parameters",
            f"        # (written by the serializer in this order: {order}).",
            "        return {",
            *self._attrs_dict("        "),
            "        }",
        ]

    def _op_convert(self):
        s = self.spec
        order = ", ".join(p.name for p in s.params)
        lines = ["", "    def convert(self, ctx, node, inputs):"]
        for i in s.const_inputs:
            lines += [
                f"        # input {i} is a constant: initializers become Const layers",
                f"        if ctx.is_initializer(inputs[{i}]):",
                f"            ctx.add_const(inputs[{i}], ctx.extract_const(inputs[{i}], False), node)",
                f"        elif not ctx.model.is_static_tensor(inputs[{i}]):",
                "            raise ConversionError(",
                f'                f"[ERROR] {s.name}: input {i} must be a constant in {{node.name}}"',
                "            )",
            ]
        lines.append(f"        layer_inputs = [ctx.graph.resolve(inputs[i]) for i in range({s.nb_inputs})]")
        if s.params:
            lines += [
                f"        # {s.marker}: map the ONNX attributes to the SADL parameters",
                f"        # (written by the serializer in this order: {order}).",
                "        attrs = {",
                *self._attrs_dict("        "),
                "        }",
                f"        self.emit(ctx, node, OpType.{s.name}, layer_inputs, **attrs)",
            ]
        else:
            lines.append(f"        self.emit(ctx, node, OpType.{s.name}, layer_inputs)")
        return lines

    def _axis_note(self):
        s = self.spec
        return [
            "",
            f"    # {s.marker}: NCHW models (PyTorch): remap axes given in NCHW to NHWC,",
            "    # e.g. in convert():",
            "    #     if len(ctx.model.shape(inputs[0]) or []) == 4:",
            "    #         axis = self.nchw_axis_to_nhwc(axis)",
            "    # (see gather_converter.py, concat_converter.py)",
        ]

    def _annotate(self):
        s = self.spec
        return [
            "",
            "    def annotate(self, annotator, node, data_layout):",
            "        # NCHW models: the layer receives NCHW data, its output goes back to NHWC",
            "        # (see reduce_mean_converter.py).",
            f"        # {s.marker}: check that the layer is correct on NCHW data",
            '        if annotator.global_layout == "nchw":',
            "            annotation = annotator.annotations[node.name]",
            '            annotation.transpose_before_in0 = "nchw"',
            "            annotation.to_nhwc_after_out = True",
        ]

    def _required_attribute(self):
        s = self.spec
        return [
            "",
            "    def _required(self, node, name):",
            "        attr = self.attribute(node, name)",
            "        if attr is None:",
            f'            raise ConversionError(f"[ERROR] {s.name}: missing attribute {{name}} in {{node.name}}")',
            "        return attr",
        ]

    # --- onnx2sadl/writer/xxx_serializer.py ---------------------------------------
    def serializer(self):
        s = self.spec
        layout = ", ".join(f"{p.name} ({p.describe()})" for p in s.params)
        if s.internal_quantizer:
            layout += ", then the internal quantizer (int32, written by SadlWriter)"
        fixed = [p for p in s.params if p.fixed_size is not None]
        imports = ["from .layer_serializer import LayerSerializer"]
        if fixed:
            imports.insert(0, "from ..errors.conversion_error import ConversionError")
        lines = [
            "",
            "",
            "",
            f"class {s.name}Serializer(LayerSerializer):",
            f'    """{s.name} parameters, read by {s.name}<T>::loadInternal in the same order:',
            "",
            f"    {layout}.",
            '    """',
            "",
        ]
        if s.internal_quantizer:
            lines += ["    writes_quantizer = True", ""]
        lines.append("    def write(self, stream, node):")
        for p in fixed:
            lines += [
                f'        if len(node["{p.name}"]) != {p.fixed_size}:',
                f'            raise ConversionError("[ERROR] {s.name}: {p.name} needs {p.fixed_size} values")',
            ]
        for p in s.params:
            lines.append(f"        {p.serializer_line()}")
        return self.HEADER + "\n" + "\n".join(imports) + "\n".join(lines) + "\n"

    # --- sadl2onnx/emitters/xxx_emitter.py ----------------------------------------
    def emitter(self):
        s = self.spec
        if s.emitter == "nchw":
            return self._nchw_emitter()
        params = ", ".join(f'layer["{p.name}"]' for p in s.params) or "none"
        return self.HEADER + "\n".join([
            "",
            "from onnx2sadl.types.op_type import OpType",
            "",
            "from .layer_emitter import LayerEmitter",
            "",
            "",
            f"class {s.name}Emitter(LayerEmitter):",
            f'    """SADL {s.name} -> ONNX {s.emitter_onnx_op}, generated by tools/new_layer.py.',
            "",
            "    The ONNX graph is NHWC, like SADL: an ONNX op defined on NCHW tensors must be",
            "    wrapped with self.to_nchw / self.to_nhwc (see pool_emitter.py).",
            f"    {s.marker}: check the emitted ONNX nodes (CONTRIBUTE.md 5.2).",
            '    """',
            "",
            f"    sadl_ops = (OpType.{s.name},)",
            "",
            "    def emit(self, ctx, layer):",
            "        inputs = self.inputs(ctx, layer)",
            f"        # parameters: {params}",
            f'        return ctx.builder.add_node("{s.emitter_onnx_op}", inputs, layer.name)',
        ]) + "\n"

    def _nchw_emitter(self):
        s = self.spec
        return self.HEADER + "\n".join([
            "",
            "from onnx2sadl.types.op_type import OpType",
            "",
            "from .nchw_op_emitter import NchwOpEmitter",
            "",
            "",
            f"class {s.name}Emitter(NchwOpEmitter):",
            f'    """SADL {s.name} -> ONNX {s.emitter_onnx_op} computed in NCHW, generated by tools/new_layer.py.',
            "",
            f"    {s.marker}: check the ONNX attributes (CONTRIBUTE.md 5.2).",
            '    """',
            "",
            "    def __init__(self):",
            f'        super().__init__(OpType.{s.name}, "{s.emitter_onnx_op}")',
            "",
            "    def attributes(self, layer):",
            "        attrs = super().attributes(layer)",
            *[f'        attrs["{p.name}"] = layer["{p.name}"]' for p in s.params],
            "        return attrs",
        ]) + "\n"

    # --- registry entries -----------------------------------------------------------
    def serializer_entry(self):
        s = self.spec
        kind = s.serializer_kind
        if kind == "int_attrs":
            return f"OpType.{s.name}: IntAttrsSerializer({', '.join(repr(p.name) for p in s.params)}),".replace("'", '"')
        if kind == "quantized":
            return f"OpType.{s.name}: QuantizedLayerSerializer(),"
        return f"OpType.{s.name}: {s.name}Serializer(),"

    def reader_entry(self):
        s = self.spec
        args = [f'"{p.reader_field()}"' for p in s.params]
        if s.internal_quantizer:
            args.append("reads_quantizer=True")
        return f"OpType.{s.name}: ListParamsReader({', '.join(args)}),"

    def emitter_entry(self):
        s = self.spec
        if s.needs_emitter_file:
            return f"{s.name}Emitter(),"
        cls = "SimpleOpEmitter" if s.emitter == "simple" else "NchwOpEmitter"
        return f'{cls}(OpType.{s.name}, "{s.emitter_onnx_op}"),'

    # --- utests/models/xxx_pytorch.py ---------------------------------------------
    def test_model(self):
        s = self.spec
        variable = [i for i in range(s.nb_inputs) if i not in s.const_inputs]  # graph inputs
        args = ", ".join(f"x{i}" if i else "x" for i in variable)
        inputs = "(" + ", ".join(["torch.rand(1, 4, 8, 8)"] * len(variable)) + ("," if len(variable) == 1 else "") + ")"
        names = ", ".join(f'"x{i}"' if i else '"x"' for i in variable)
        constants = [f"        c{i} = torch.ones(1, 4, 1, 1)  # constant input {i}: exported as an initializer"
                     for i in s.const_inputs]
        return self.HEADER + "\n".join([
            f'"""Export utests/models/{s.py_name}.onnx, the test model of the SADL {s.name} layer.',
            "",
            f"{s.marker}: make forward() use the operation (CONTRIBUTE.md 6.1). Cover each",
            "mode/parameter; constant inputs should be tensors created in forward().",
            "Then: python utests/models/" + f"{s.py_name}_pytorch.py && ./utests/utest.sh utests/models/{s.py_name}.onnx",
            '"""',
            "",
            "import os",
            "",
            "import torch",
            "",
            "",
            "class Model(torch.nn.Module):",
            f"    def forward(self, {args}):",
            *constants,
            f"        return x  # {s.marker}: the {', '.join(s.onnx_ops)} operation",
            "",
            "",
            'if __name__ == "__main__":',
            f'    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "{s.py_name}.onnx")',
            f"    torch.onnx.export(Model(), {inputs}, out, input_names=[{names}],",
            '                      output_names=["y"], opset_version=13, dynamo=False)',
            '    print("written", out)',
        ]) + "\n"
