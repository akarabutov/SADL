class CppTemplates:
    """C++ code of a new layer: CPU header, CUDA header and registration snippets."""

    def __init__(self, spec, license_header):
        self.spec = spec
        self.header = license_header

    # --- shared pieces ----------------------------------------------------------
    def _members(self):
        lines = [f"  {p.cpp_decl()}   // {p.describe()}" for p in self.spec.params]
        if self.spec.internal_quantizer:
            lines.append("  int32_t m_q = 0;   // internal quantizer (set by naive_quantization)")
        return lines

    def _extra_includes(self):
        return ["#include <array>"] if any(p.fixed_size for p in self.spec.params) else []

    def _load_body(self):
        """Body of loadInternal: reads exactly what the converter serializer writes."""
        s = self.spec
        if not s.has_payload:
            return ["  return true;"]
        lines = ["  // parameters, in the order written by the converter (onnx2sadl serializer)"]
        for p in s.params:
            lines += p.cpp_read(s.name)
        if s.internal_quantizer:
            lines.append("  file.read((char *) &m_q, sizeof(m_q));")
        lines += [
            "  if (!file)",
            "  {",
            f'    std::cerr << "[ERROR] {s.name}: cannot read the parameters" << std::endl;',
            "    return false;",
            "  }",
            f"  // {s.marker}: check the parameter values, return false with a message if invalid",
            "  return true;",
        ]
        return lines

    def _load_signature(self):
        return "std::istream &file, Version" if self.spec.has_payload else "std::istream &, Version"

    def _init_body(self, indent="  "):
        s = self.spec
        lines = [
            f"if (in.size() != {s.nb_inputs})",
            "{",
            f'  std::cerr << "[ERROR] {s.name}: expected {s.nb_inputs} input(s), got " << in.size() << std::endl;',
            "  return false;",
            "}",
            f"// {s.marker}: check the input shapes and parameters (batch size 1),",
            "// then size the output (here: same dims as input 0)",
            "m_out.resize(in[0]->dims());",
            "m_initDone = true;",
            "return true;",
        ]
        return [indent + line for line in lines]

    def _inputs_comment(self):
        s = self.spec
        lines = []
        for i in range(1, s.nb_inputs):
            kind = "constant (Const layer)" if i in s.const_inputs else "tensor"
            lines.append(f"  // in[{i}]: {kind}")
        return lines

    # --- sadl/layer_xxx.h -------------------------------------------------------
    def cpu_layer(self):
        s = self.spec
        m = s.marker
        dump = ["  DUMP_MODEL_EXT;   // dump() in sample/dumper.h"] if s.has_payload else []
        q_comment = []
        if s.internal_quantizer:
            q_comment = ["  // m_q is the internal quantizer: shift the result by m_q (see layer_matmul.h)"]
        lines = [
            "#pragma once",
            *self._extra_includes(),
            '#include "layer.h"',
            "",
            "namespace sadl",
            "{",
            "namespace layers",
            "{",
            f"// SADL layer {s.name} (id {s.sadl_id}), generated by tools/new_layer.py.",
            f"// {m}: implement init() and apply() (CONTRIBUTE.md 1.2).",
            f"template<typename T> class {s.name} : public Layer<T>",
            "{",
            "public:",
            "  using Layer<T>::Layer;",
            "  using Layer<T>::m_out;   // to avoid this->",
            "  using Layer<T>::m_initDone;",
            "",
            "  virtual bool apply(std::vector<Tensor<T> *> &in) override;",
            "  virtual bool init(const std::vector<Tensor<T> *> &in) override;",
            "",
            "protected:",
            "  virtual bool loadInternal(std::istream &file, Version v) override;",
            *self._members(),
            *dump,
            "};",
            "",
            "// called at each inference: compute m_out from the inputs",
            f"template<typename T> bool {s.name}<T>::apply(std::vector<Tensor<T> *> &in)",
            "{",
            "  auto scope = makeLayerExecutionScope(m_out, in);   // memory management, mandatory",
            f"  assert(in.size() == {s.nb_inputs});",
            "  const Tensor<T> &A = *in[0];",
            *self._inputs_comment(),
            f"  // {m}: output fixed-point precision. With several inputs, align their",
            "  // quantizers first (see layer_add.h, layer_clip.h, layer_mul.h).",
            *q_comment,
            "  m_out.quantizer = A.quantizer;",
            "  for (int k = 0; k < (int) m_out.size(); ++k)",
            "  {",
            "    typename ComputationType<T>::type z = A[k];   // wider type for integer models",
            f"    // {m}: compute the output value (identity for now)",
            "    COUNTERS(z);",
            "    SATURATE(z);",
            "    m_out[k] = static_cast<T>(z);",
            "  }",
            "  return true;",
            "}",
            "",
            "// called once at model initialization: check the inputs and size m_out",
            f"template<typename T> bool {s.name}<T>::init(const std::vector<Tensor<T> *> &in)",
            "{",
            *self._init_body(),
            "}",
            "",
            "// reads the parameters, byte for byte as written by the converter",
            f"template<typename T> bool {s.name}<T>::loadInternal({self._load_signature()})",
            "{",
            *self._load_body(),
            "}",
            "",
            "}   // namespace layers",
            "}   // namespace sadl",
        ]
        return self.header + "\n".join(lines) + "\n"

    # --- sadl_cuda/layer_xxx.h --------------------------------------------------
    def cuda_layer(self):
        s = self.spec
        m = s.marker
        gpu = s.cuda == "gpu"
        kernel = []
        if gpu:
            kernel = [
                "#ifdef __CUDACC__",
                f"__global__ static void {s.py_name}_kernel(const int16_t *src, int16_t *dst, int n)",
                "{",
                "  int i = blockIdx.x * blockDim.x + threadIdx.x;",
                "  if (i < n)",
                "  {",
                "    int32_t z = src[i];",
                f"    // {m}: same integer computation as the CPU int16_t layer (bit-exact)",
                "    dst[i] = (int16_t) SADL_CUDA_SAT(z);",
                "  }",
                "}",
                "#endif",
                "",
            ]
        host_loop = [
            "for (int i = 0; i < size; ++i)",
            "{",
            "  int32_t z = (*in[0])[i];",
            f"  // {m}: same integer computation as the CPU int16_t layer (bit-exact)",
            "  m_out[i] = static_cast<T>(SADL_CUDA_SAT(z));",
            "}",
        ]
        if gpu:
            body = [
                "#ifdef __CUDACC__",
                f"    {s.py_name}_kernel<<<gridDim1D(size, SADL_CUDA_BLOCK_SIZE), SADL_CUDA_BLOCK_SIZE>>>(",
                "      in[0]->dev_data(), m_out.dev_data(), size);",
                "#else",
                *["    " + line for line in host_loop],
                "#endif",
            ]
        else:
            body = ["    " + line for line in host_loop]
        lines = [
            "#pragma once",
            *self._extra_includes(),
            '#include "layer.h"',
            *(['#include "cuda_utils.h"'] if gpu else []),
            "",
            "namespace sadl_cuda",
            "{",
            "namespace layers",
            "{",
            "",
            *kernel,
            f"// CUDA version of sadl/{s.cpp_header} ({'GPU kernel' if gpu else 'run on the host'}),",
            "// generated by tools/new_layer.py. Only int16_t models run on CUDA.",
            f"// {m}: implement it (CONTRIBUTE.md 3.1).",
            f"template<typename T> class {s.name} : public Layer<T>",
            "{",
            "public:",
            "  using Layer<T>::Layer;",
            "  using Layer<T>::m_out;",
            "  using Layer<T>::m_initDone;",
            "",
            *(["  bool isGpuLayer() const override { return true; }", ""] if gpu else []),
            "  virtual bool apply(std::vector<Tensor<T> *> &in) override",
            "  {",
            f"    assert(in.size() == {s.nb_inputs});",
            f"    m_out.quantizer = in[0]->quantizer;   // {m}: same as the CPU layer",
            "    const int size = static_cast<int>(m_out.size());",
            *body,
            "    return true;",
            "  }",
            "",
            "  virtual bool init(const std::vector<Tensor<T> *> &in) override",
            "  {",
            *self._init_body("    "),
            "  }",
            "",
            "protected:",
            f"  virtual bool loadInternal({self._load_signature()}) override",
            "  {",
            *["  " + line for line in self._load_body()],
            "  }",
            *self._members(),
            "};",
            "",
            "}   // namespace layers",
            "}   // namespace sadl_cuda",
        ]
        return self.header + "\n".join(lines) + "\n"

    # --- snippets for existing files ----------------------------------------------
    def copy_case(self):
        """sample/copy.h: copy of the parameters from the float model."""
        s = self.spec
        lines = [f"  case sadl::layers::OperationType::{s.name}:"]
        members = [p.member for p in s.params] + (["m_q"] if s.internal_quantizer else [])
        for member in members:
            lines.append(
                f"    dynamic_cast<sadl::layers::{s.name}<T> &>(layerQ).{member} = "
                f"dynamic_cast<const sadl::layers::{s.name}<float> &>(layer).{member};"
            )
        lines.append("    break;")
        return lines

    def dump_function(self):
        """sample/dumper.h: writes the parameters in the order of loadInternal."""
        s = self.spec
        lines = [f"template<typename T> bool sadl::layers::{s.name}<T>::dump(std::ostream &file)", "{"]
        for p in s.params:
            lines += p.cpp_dump()
        if s.internal_quantizer:
            lines.append("  file.write((const char *) &this->m_q, sizeof(this->m_q));")
        lines += ["  return true;", "}", ""]
        return lines

    def model_case(self, indent):
        s = self.spec
        return [
            f"{indent}case layers::OperationType::{s.name}:",
            f"{indent}  return std::unique_ptr<layers::Layer<T>>(new layers::{s.name}<T>{{ id, op }});",
            f"{indent}  break;",
        ]

    def cuda_model_case(self, indent, width):
        s = self.spec
        label = f"case OperationType::{s.name}:"
        return [f"{indent}{label.ljust(width)}return std::make_unique<{s.name}<T>>(id, op);"]
