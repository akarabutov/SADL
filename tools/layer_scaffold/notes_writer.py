from .patch import Patch


class NotesWriter:
    """NEW_LAYER_<Name>.md: what was generated and the checklist of what is left."""

    FILE_ROLES = {
        "cpp": "implement `init()` and `apply()`; `loadInternal()` is complete (CONTRIBUTE.md 1.2)",
        "cuda": "CUDA version, bit-exact with the CPU int16 layer (CONTRIBUTE.md 3.1)",
        "converter": "check the ONNX attribute mapping and the layout (CONTRIBUTE.md 4.2, 4.3)",
        "serializer": "complete; must match `loadInternal` byte for byte (CONTRIBUTE.md 4.5)",
        "emitter": "check the emitted ONNX nodes (CONTRIBUTE.md 5.2)",
        "test": "write `forward()`, then export the test model (CONTRIBUTE.md 6.1)",
    }

    def __init__(self, spec, change_set, file_roles):
        self.spec = spec
        self.changes = change_set
        self.file_roles = file_roles  # rel -> key of FILE_ROLES

    def render(self):
        s = self.spec
        out = [
            f"# New SADL layer `{s.name}` (id {s.sadl_id})",
            "",
            "Generated by `tools/new_layer.py`. This file and "
            f"`{s.config_path}` are working notes: delete them before committing "
            f"(the JSON file replays the generation: `python tools/new_layer.py --config {s.config_path}`).",
            "",
            f"Every place left to complete is marked `{s.marker}`. List them with:",
            "",
            "```shell",
            f"python tools/new_layer.py --check {s.name}",
            "```",
            "",
            "## Answers",
            "",
            "| Question | Answer |",
            "|---|---|",
            *[f"| {k} | `{v}` |" for k, v in self._answers()],
            "",
            "## Created files",
            "",
            *[f"- `{rel}`: {self.FILE_ROLES[self.file_roles[rel]]}" for rel in self.file_roles],
            "",
            "## Existing files updated",
            "",
            "| File | Change | Status |",
            "|---|---|---|",
            *[f"| `{p.rel}` | {p.description.replace('|', '/')} | {p.status} |" for p in self.changes.patches],
            "",
        ]
        manual = self.changes.manual_patches
        if manual:
            out += ["## Manual steps (the script could not place these)", ""]
            for p in manual:
                out += [f"- `{p.rel}` ({p.status}, CONTRIBUTE.md {p.section}): {p.description}", "",
                        "  ```", *["  " + line for line in p.manual], "  ```", ""]
        out += ["## Checklist", "", *self._checklist(), ""]
        return "\n".join(out)

    def _answers(self):
        s = self.spec
        params = ", ".join(f"{p.name}: {p.kind}" for p in s.params) or "none"
        return [
            ("Layer / SADL id", f"{s.name} / {s.sadl_id}"),
            ("ONNX op types", ", ".join(s.onnx_ops)),
            ("Inputs (constant)", f"{s.nb_inputs} ({', '.join(map(str, s.const_inputs)) or 'none'})"),
            ("Parameters (binary order)", params),
            ("Internal quantizer", "yes" if s.internal_quantizer else "no"),
            ("Converter base / layout", f"{s.converter_base} / {s.layout}"),
            ("Serializer", s.serializer_kind),
            ("Emitter", f"{s.emitter} -> {s.emitter_onnx_op}"),
            ("CUDA / Netron", f"{s.cuda} / {'yes' if s.netron else 'no'}"),
        ]

    def _checklist(self):
        s = self.spec
        done = self._registered()
        items = [
            ("C++ (1.1, 1.3)", "id, `layers.h`, factory in `model.h`", done("sadl/")),
            ("C++ (1.2)", f"`init()` / `apply()` in `{s.cpp_layer_path}`, float and integer types", False),
            ("C++ (2.1-2.3)", "`copy.h`, `dumper.h`, `naive_quantization.cpp`", done("sample/")),
        ]
        if s.cuda != "skip":
            items += [
                ("CUDA (3.1)", "registration", done("sadl_cuda/")),
                ("CUDA (3.1)", f"implement `{s.cuda_layer_path}`, then `./utests/check_cuda.sh --model {s.py_name}`",
                 False),
            ]
        if s.netron:
            items += [
                ("Netron (3.2)", "`sadl.OpSpec` entry" + (" and decoder" if s.has_payload else ""),
                 done("tools/netron/")),
                ("Netron (3.2)", "regenerate `tools/netron/netron-sadl.patch` and check a model in the viewer",
                 False),
            ]
        items += [
            ("ONNX -> SADL (4.1, 4.4, 4.5)", "`OpType`, `OpCatalog`, serializer", done("converter/onnx2sadl/")),
            ("ONNX -> SADL (4.2, 4.3)", f"check `{s.converter_path}`", False),
            ("ONNX -> SADL (4.6)", "`onnxopt` pass if exporters produce an unsupported pattern", False),
            ("SADL -> ONNX (5.1, 5.2)", "reader and emitter registration", done("converter/sadl2onnx/")),
            ("SADL -> ONNX (5.2)", "rule in `emitters/rank_tracker.py` if the output rank differs from input 0",
             False),
        ]
        if s.test_model:
            items += [
                ("Tests (6.1)", f"`python {s.test_model_script_path}` -> `utests/models/{s.py_name}.onnx`", False),
                ("Tests (6.2)", f"`./utests/utest.sh utests/models/{s.py_name}.onnx`, then add it to "
                                "`utests/check.sh`", False),
            ]
        items += [
            ("Tests (6.3)", "existing models convert byte-identically; SADL -> ONNX round trip matches", False),
            ("Style (6.4)", "`flake8 converter/`, `black converter/`, `clang-format -i` on the new headers", False),
        ]
        return [f"- [{'x' if ok else ' '}] {area}: {text}" for area, text, ok in items]

    def _registered(self):
        def done(prefix):
            patches = [p for p in self.changes.patches if p.rel.startswith(prefix)]
            return bool(patches) and all(p.status in (Patch.APPLIED, Patch.PRESENT) for p in patches)

        return done
