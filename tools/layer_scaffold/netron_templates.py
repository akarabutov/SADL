class NetronTemplates:
    """tools/netron/sadl.js: OpSpec entry and payload decoder (CONTRIBUTE.md 3.2)."""

    NAME_WIDTH = 18  # "  Name:" column of sadl.OpSpec

    def __init__(self, spec):
        self.spec = spec

    def op_spec_entry(self, indent="  "):
        s = self.spec
        payload = "true " if s.has_payload else "false"
        return f"{indent}{(s.name + ':').ljust(self.NAME_WIDTH)}{{ id: {s.sadl_id}, payload: {payload} }},"

    def decoder(self):
        """Decoder reading exactly the bytes of loadInternal ([] if no payload)."""
        s = self.spec
        if not s.has_payload:
            return []
        values = [f"    {{ name: '{p.name}', value: {p.netron_value()} }}" for p in s.params]
        if s.internal_quantizer:
            values.append("    { name: 'q', value: cursor.readI32() }")
        values = [v + "," for v in values[:-1]] + values[-1:]
        return [
            f"// {s.name} (generated by tools/new_layer.py)",
            f"dec[sadl.OpCode.{s.name}] = sadl.decode.decodeOp('{s.name}', ({{ cursor }}) => {{",
            "  return [",
            *values,
            "  ];",
            "});",
            "",
        ]
